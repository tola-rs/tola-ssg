//! `[vendor]` section configuration.

use std::path::{Path, PathBuf};

use serde::{Deserialize, Serialize};
use tola_config::Config;

use crate::config::ConfigDiagnostics;

/// Keep the modules, packages, and icon collections a build reads with the site.
#[derive(Debug, Clone, Default, Serialize, Deserialize, Config)]
#[serde(default)]
#[config(section = "vendor")]
pub struct VendorConfig {
    /// Directory, relative to the site root, where `tola vendor` freezes the inputs a build
    /// selected.
    pub path: Option<PathBuf>,
}

impl VendorConfig {
    /// What `tola help "[vendor]"` adds under its table.
    pub const HELP: &'static str = "\
`tola vendor` freezes the external inputs selected by a production build into this directory.
Declare `path` before using the command:

```toml
[vendor]
path = \"vendor\"
```

`path` must be a real directory below the site root and outside `.tola`.

Preparation keeps the previous copy until the new one verifies, then replaces it; an interrupted
replacement is completed by the next run, and a build refuses to run until then. Working files
live in a sibling directory whose name starts with `.` and ends with `-swap`.

Vendoring runs no hook stage and publishes nothing. Its verification build proves the frozen
inputs resolve and compile under `--pure`, not that the site is valid: `before-build` files must
already exist, `generate-outputs` files are regenerated by each build, and link checks belong to
`tola check`.

Tola replaces these three subdirectories as a whole; other files below `path` stay untouched:

- `modules/` — one directory per declared module alias, holding the module's `subdir` contents
  at the commit `tola.lock` records
- `typst-packages/` — resolved packages under `{namespace}/{name}/{version}/`, including packages
  selected from host roots or `--package-path`
- `icons/` — one `<namespace>.json` per configured `remote-json` collection

Compiler fonts are not vendored. Copying a host font into the repository would redistribute a
file Tola cannot license-check; keep fonts in `[typst.fonts] paths`.

Keep the site's own sources outside these directories. A `--pure` build reads each declared module
from its frozen copy below `modules/`; packages of every namespace — including `@preview` —
resolve from vendor before host roots, and a remote icon collection prefers its vendored copy.
Commit these inputs with the site:

```sh
tola vendor --dry-run   # prepare and verify without replacing vendor
tola vendor             # install the verified dependencies
tola build --pure       # build from site-owned inputs
```

`--refresh` resolves every input again from host roots, caches, and the network instead of the
installed copy; a refresh that cannot resolve an input keeps the previous copy. `--dry-run` leaves
the copy unchanged.

`--offline` refuses network requests but permits host package roots, caches, and system fonts.
`--pure` reads only the site's own sources, the vendored inputs, and `tola.lock`: host package
roots, `.tola/`, system fonts, and paths outside the site are refused, including through
symlinks. Embedded packages and fonts stay available.

These flags restrict Tola's reads, not hook commands or their toolchains: to reproduce the whole
build elsewhere, pin each hook's toolchain or commit the files it generates.";

    /// The directory a site keeps its vendored module sources in.
    pub fn modules(&self) -> Option<PathBuf> {
        self.path.as_ref().map(|path| path.join("modules"))
    }

    /// The directory one declared module's frozen contents live in.
    pub fn module(&self, alias: &str) -> Option<PathBuf> {
        self.modules().map(|modules| modules.join(alias))
    }

    /// The directory a site keeps its vendored Typst packages in.
    pub fn typst_packages(&self) -> Option<PathBuf> {
        self.path.as_ref().map(|path| path.join("typst-packages"))
    }

    /// The directory a site keeps its vendored icon collections in.
    pub fn icons(&self) -> Option<PathBuf> {
        self.path.as_ref().map(|path| path.join("icons"))
    }

    /// The file one vendored icon collection is frozen to.
    pub fn icon_collection(&self, namespace: &str) -> Option<PathBuf> {
        self.icons()
            .map(|icons| icons.join(format!("{namespace}.json")))
    }

    /// Validate the path before site-root normalization.
    pub fn validate_paths(&self, diagnostics: &mut ConfigDiagnostics) {
        let Some(path) = &self.path else {
            return;
        };
        let accepted = super::path::validate_site_relative_path(
            path,
            Self::FIELDS.path.as_str(),
            Self::FIELDS.path,
            diagnostics,
        );
        if !accepted {
            return;
        }
        if !path
            .components()
            .any(|part| matches!(part, std::path::Component::Normal(_)))
        {
            diagnostics.error(
                Self::FIELDS.path,
                "`vendor.path` must name a directory below the site root",
            );
            return;
        }
        if super::path::enters_internal_directory(path) {
            diagnostics.error_with_help(
                Self::FIELDS.path,
                format!(
                    "`vendor.path` `{}` is inside Tola's `.tola` directory",
                    super::path::declared_path(path)
                ),
                "write a directory outside `.tola`",
            );
        }
    }

    /// Input aliases must not turn the vendor directory into machine or disposable state.
    pub(crate) fn validate_internal_boundaries(
        &self,
        root: &Path,
        diagnostics: &mut ConfigDiagnostics,
    ) {
        let Some(path) = &self.path else {
            return;
        };
        let physical_root = tola_input::normalize_existing_prefix(root);
        let physical_path = tola_input::normalize_existing_prefix(path);
        if physical_path == physical_root || !physical_path.starts_with(&physical_root) {
            diagnostics.error(
                Self::FIELDS.path,
                "`vendor.path` must stay below the site root after resolving links",
            );
        }
        if super::path::reaches_internal_directory(root, path) {
            diagnostics.error(
                Self::FIELDS.path,
                format!(
                    "`vendor.path` `{}` is inside Tola's `.tola` directory",
                    tola_diagnostic::display_path(path, root)
                ),
            );
        }
    }

    /// Normalize the path relative to the site root.
    pub fn normalize(&mut self, root: &Path) {
        if let Some(path) = &mut self.path {
            *path = root.join(&*path);
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::config::ConfigDiagnostics;

    #[test]
    fn vendor_paths_stay_below_site() {
        for declared in [".tola/vendor", "../vendor", "."] {
            let config = VendorConfig {
                path: Some(PathBuf::from(declared)),
            };
            let mut diagnostics = ConfigDiagnostics::new();
            config.validate_paths(&mut diagnostics);
            assert!(
                diagnostics.into_result().is_err(),
                "{declared} must be rejected"
            );
        }
    }

    #[test]
    fn internal_directory_reserved_any_spelling() {
        let site = tempfile::TempDir::new().unwrap();
        for declared in [".tola/vendor", ".TOLA/vendor", ".Tola/vendor"] {
            let config = VendorConfig {
                path: Some(PathBuf::from(declared)),
            };
            let mut diagnostics = ConfigDiagnostics::new();
            config.validate_paths(&mut diagnostics);
            assert!(
                diagnostics.into_result().is_err(),
                "{declared} must be rejected"
            );

            let resolved = VendorConfig {
                path: Some(site.path().join(declared)),
            };
            let mut diagnostics = ConfigDiagnostics::new();
            resolved.validate_internal_boundaries(site.path(), &mut diagnostics);
            assert!(
                diagnostics.into_result().is_err(),
                "{declared} must be rejected after resolution"
            );
        }
    }

    #[cfg(unix)]
    #[test]
    fn vendor_alias_cannot_escape_site() {
        let site = tempfile::TempDir::new().unwrap();
        let outside = tempfile::TempDir::new().unwrap();
        let path = site.path().join("vendor");
        std::os::unix::fs::symlink(outside.path(), &path).unwrap();
        let config = VendorConfig { path: Some(path) };
        let mut diagnostics = ConfigDiagnostics::new();
        config.validate_internal_boundaries(site.path(), &mut diagnostics);
        assert!(diagnostics.into_result().is_err());
    }
}
