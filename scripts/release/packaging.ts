export interface VerifyDirectoryOptions {
  readonly target?: TargetName
  readonly verifyChecksums?: boolean
  /** Targets whose archives the directory must contain exactly. Defaults to every target. */
  readonly targets?: readonly TargetName[]
}

export interface ReleaseBuildOptions {
  /** The workspace whose sources are built. */
  readonly root: string
  /** Directory receiving the finished archives. */
  readonly output: string
  /** Targets to build; defaults to the one target this host produces natively. */
  readonly targets?: readonly TargetName[]
}

export async function verifyDirectory(
  directory: string,
  version: string,
  options: VerifyDirectoryOptions = {},
  signal?: AbortSignal,
): Promise<ArchiveDigests> {
  signal?.throwIfAborted()
  await ordinaryDirectory(directory)
  const selected = options.target === undefined ? (options.targets ?? TARGET_NAMES) : [options.target]
  const expected = new Set<string>(selected.map((name) => archiveName(name, version)))
  const actual = new Set(await readdir(directory))
  const missing = [...expected].filter((name) => !actual.has(name)).sort()
  const missingLicenses = Object.keys(LICENSE_FILES).filter((name) => !actual.has(name)).sort()
  const unexpected = [...actual]
    .filter((name) => name !== 'checksums.txt' && !(name in LICENSE_FILES) && !expected.has(name))
    .sort()
  assert(
    missing.length === 0 && missingLicenses.length === 0 && unexpected.length === 0,
    `release set mismatch: missing ${JSON.stringify(missing)}, missing license files ${
      JSON.stringify(missingLicenses)
    }, unexpected ${JSON.stringify(unexpected)}`,
  )
  if (actual.has('checksums.txt')) await regularFile(join(directory, 'checksums.txt'))
  for (const name of Object.keys(LICENSE_FILES)) await regularFile(join(directory, name))
  const digests = new Map<string, string>()
  for (const name of selected) {
    const archive = archiveName(name, version)
    digests.set(archive, await verifyArchive(join(directory, archive), TARGETS[name], version, signal))
  }
  if (options.verifyChecksums !== false && actual.has('checksums.txt')) {
    await checkChecksums(join(directory, 'checksums.txt'), digests, signal)
  }
  signal?.throwIfAborted()
  return digests
}

/**
 * Build one release target with Cargo and package its binary.
 *
 * The release profile's fat LTO is requested here so the workspace default stays thin.
 */
export async function build(
  targetName: TargetName,
  version: string,
  options: ReleaseBuildOptions,
  signal?: AbortSignal,
): Promise<void> {
  signal?.throwIfAborted()
  console.log(`Building ${targetName}`)
  const result = await runProcess(
    'cargo',
    ['build', '--release', '--locked', '-p', 'tola', '--target', targetName],
    {
      env: {
        ...process.env,
        CARGO_PROFILE_RELEASE_LTO: 'fat',
        // A Linux archive is the static one: the vendored OpenSSL and the C runtime both link
        // statically. The musl target does this by default; naming it makes the requirement
        // unmistakable, and a dynamic input then fails the link instead of the archive check.
        ...(targetName.endsWith('-musl')
          ? { OPENSSL_STATIC: '1', RUSTFLAGS: '-C target-feature=+crt-static' }
          : {}),
      },
      stderr: 'inherit',
      ...(signal === undefined ? {} : { signal }),
    },
  )
  signal?.throwIfAborted()
  assert(!result.timedOut && result.exitCode === 0, `Cargo build failed (${result.exitCode})`)
  const source = join(options.root, 'target', targetName, 'release', TARGETS[targetName].binary)
  await packageBinary(source, options.output, targetName, version, signal)
}

export async function packageBinary(
  source: string,
  output: string,
  targetName: TargetName,
  version: string,
  signal?: AbortSignal,
): Promise<void> {
  signal?.throwIfAborted()
  const target = TARGETS[targetName]
  const archive = archiveName(targetName, version)
  await regularFile(source)
  signal?.throwIfAborted()
  await mkdir(output, { recursive: true })
  await ordinaryDirectory(output)
  const destination = join(output, archive)
  await ordinaryDestination(destination)
  signal?.throwIfAborted()
  const staging = await mkdtemp(join(output, `.${targetName}-`))
  try {
    const staged = join(staging, archive)
    await createArchive(source, staged, target, signal)
    await verifyArchive(staged, target, version, signal)
    await ordinaryDirectory(output)
    await ordinaryDestination(destination)
    signal?.throwIfAborted()
    await rename(staged, destination)
  } finally {
    await rm(staging, { recursive: true, force: true })
  }
  signal?.throwIfAborted()
  console.log(`Wrote ${destination}`)
}

export async function checksums(
  directory: string,
  version: string,
  targets: readonly TargetName[],
  signal?: AbortSignal,
): Promise<ArchiveDigests> {
  signal?.throwIfAborted()
  // Rebuilds can leave stale checksums. Verify every archive before replacing the complete list.
  const digests = await verifyDirectory(directory, version, { verifyChecksums: false, targets }, signal)
  signal?.throwIfAborted()
  const staging = await mkdtemp(join(directory, '.checksums-'))
  const destination = join(directory, 'checksums.txt')
  try {
    const temporary = join(staging, 'checksums.txt')
    await writeFile(temporary, checksumContents(digests), {
      encoding: 'ascii',
      flag: 'wx',
      mode: 0o600,
      ...(signal === undefined ? {} : { signal }),
    })
    await checkChecksums(temporary, digests, signal)
    await ordinaryDirectory(directory)
    await ordinaryDestination(destination)
    signal?.throwIfAborted()
    await rename(temporary, destination)
  } finally {
    await rm(staging, { recursive: true, force: true })
  }
  signal?.throwIfAborted()
  console.log(`Wrote ${destination}`)
  return digests
}

/**
 * Build and package the selected targets, then write their checksums.
 *
 * A host builds only its own target by default: the other targets need their own runner, which
 * the release workflow supplies. Every selected target is built before any checksum is written.
 */
export async function buildAll(
  version: string,
  options: ReleaseBuildOptions,
  signal?: AbortSignal,
): Promise<void> {
  signal?.throwIfAborted()
  const targets = options.targets ?? [hostTargetName()]
  const outcomes = await Promise.allSettled(
    targets.map(async (target) => {
      try {
        await build(target, version, options, signal)
      } catch (error) {
        if (
          signal?.aborted &&
          (error === signal.reason || (error instanceof Error && error.name === 'AbortError'))
        ) {
          throw signal.reason
        }
        throw new Error(`Failed to build ${target}: ${errorMessage(error)}`, { cause: error })
      }
    }),
  )
  const failures: Error[] = []
  for (const outcome of outcomes) {
    if (outcome.status === 'rejected') {
      if (signal?.aborted && outcome.reason === signal.reason) continue
      failures.push(outcome.reason instanceof Error ? outcome.reason : new Error(String(outcome.reason)))
    }
  }
  if (failures.length > 0) {
    throw new AggregateError(failures, failures.map((error) => error.message).join('\n'))
  }
  signal?.throwIfAborted()
  await writeLicenseFiles(options, signal)
  await checksums(options.output, version, targets, signal)
}

/** Place the license material beside the archives, replacing any previous copies. */
export async function writeLicenseFiles(options: ReleaseBuildOptions, signal?: AbortSignal): Promise<void> {
  signal?.throwIfAborted()
  await mkdir(options.output, { recursive: true })
  await ordinaryDirectory(options.output)
  for (const [name, relative] of Object.entries(LICENSE_FILES)) {
    signal?.throwIfAborted()
    let contents: Buffer
    try {
      contents = await readFile(join(options.root, relative))
    } catch (error) {
      throw new Error(
        `missing ${relative}; run \`just licenses\` before building the release (${errorMessage(error)})`,
        { cause: error },
      )
    }
    await replaceLicenseFile(options.output, name, contents, signal)
  }
}

async function replaceLicenseFile(
  directory: string,
  name: string,
  contents: Buffer,
  signal?: AbortSignal,
): Promise<void> {
  const staging = await mkdtemp(join(directory, '.licenses-'))
  try {
    const temporary = join(staging, name)
    await writeFile(temporary, contents, {
      flag: 'wx',
      mode: 0o600,
      ...(signal === undefined ? {} : { signal }),
    })
    await ordinaryDirectory(directory)
    const destination = join(directory, name)
    await ordinaryDestination(destination)
    signal?.throwIfAborted()
    await rename(temporary, destination)
  } finally {
    await rm(staging, { recursive: true, force: true })
  }
}
